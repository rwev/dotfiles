grok_notification_commands_are_notify_only() {
  jq -e '
    def commands: [.. | objects | .command? // empty | select(type == "string")];
    (commands | length) > 0 and (commands | all(. == "../notify.sh"))
  ' "$1" >/dev/null 2>&1
}

# Drop the notification hook this installer used to copy.
# Leave custom hook files alone, and never follow a symlinked hooks directory.
remove_managed_grok_notifications() {
  local notify="$GROK_DIR/notify.sh" hooks="$GROK_DIR/hooks" dest
  dest="$hooks/notifications.json"
  if [[ -L "$notify" ]]; then
    info "Removing $notify"
    run rm -- "$notify"
  fi
  if [[ -L "$hooks" || ! -f "$dest" || -L "$dest" ]]; then
    return 0
  fi
  if grok_notification_commands_are_notify_only "$dest"; then
    info "Removing $dest"
    run rm -- "$dest"
  fi
}

install_grok() {
  ensure_directory "$GROK_DIR"
  install_instructions "$GROK_DIR/AGENTS.md" true grok
  install_native_agents grok "$GROK_DIR/agents"
  install_grok_config "$GROK_DIR/config.toml"
  link_file "$DOTFILES_DIR/.grok/statusline.sh" "$GROK_DIR/statusline.sh"
  remove_managed_grok_notifications
}

summarize_harnesses() {
  local tool installed="" excluded="" example
  for tool in claude opencode copilot grok; do
    if [[ ",$TOOLS," == *",$tool,"* ]]; then
      installed+="${installed:+, }$tool"
    else
      excluded+="${excluded:+, }$tool"
    fi
  done
  if $DRY_RUN; then
    info "Would install harnesses: ${installed:-none (shared layer only)}"
  else
    success "Installed harnesses: ${installed:-none (shared layer only)}"
  fi
  info "Excluded harnesses: ${excluded:-none}"
  example="${installed//, /,}"
  [[ -z "$excluded" ]] || info "List excluded harnesses in --tools to install them, e.g. --tools=${example:+$example,}${excluded%%,*}"
}

install_agents() {
  local tool
  command -v jq &>/dev/null || { error "jq is required for agent installation"; return 1; }
  install_shared_agents
  for tool in "${SELECTED_TOOLS[@]}"; do
    case "$tool" in
      claude) install_claude ;;
      opencode) install_opencode ;;
      copilot) install_copilot ;;
      grok) install_grok ;;
    esac
  done
  summarize_harnesses
}
