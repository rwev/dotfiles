markdown_body() {
  awk 'NR == 1 && $0 == "---" { front = 1; next } front && $0 == "---" { front = 0; next } !front { print }' "$1"
}

preserve_generated_destination() {
  local dest="$1" legacy="${2:-}"
  if [[ -L "$dest" ]]; then
    if [[ -n "$legacy" && "$(readlink "$dest")" == "$legacy" ]]; then
      run rm "$dest"
    else
      backup_file "$dest"
    fi
  elif [[ -e "$dest" ]] && ! grep -q -e '^<!-- Generated by dotfiles/install.sh -->$' -e '^# Generated by dotfiles/install.sh$' "$dest"; then
    backup_file "$dest"
  fi
}

install_generated_file() {
  local dest="$1" renderer="$2" preserve="$3" preserve_arg="$4" tmp
  shift 4
  tmp="$(mktemp "${dest}.tmp.XXXXXX")" || return 1
  if ! "$renderer" "$@" > "$tmp"; then
    rm "$tmp"
    error "Failed to generate $dest"
    return 1
  fi
  "$preserve" "$dest" "$preserve_arg" "$@" || { rm "$tmp"; return 1; }
  mv "$tmp" "$dest" || { rm "$tmp"; return 1; }
}

render_instructions() {
  local persona="$1" local_override="$2" harness="${3:-}"
  printf '<!-- Generated by dotfiles/install.sh -->\n\n'
  cat "$DOTFILES_DIR/.agents/AGENTS.md" || return
  if [[ "$persona" == true ]]; then
    printf '\n'
    cat "$DOTFILES_DIR/.agents/personas/my-humble-servant.md" || return
  fi
  if [[ "$harness" == grok ]]; then
    cat <<'EOF'

## Grok review context

Supply the full diff and test results to `_my-reviewer` and
`_my-security-reviewer`. Include task requirements and the task baseline.
These agents cannot run git or tests. A commit range alone is not enough.
If context is missing, have the reviewer request the missing context.
EOF
  fi
  if [[ -f "$local_override" ]]; then
    printf '\n'
    cat "$local_override" || return
  fi
}

preserve_instructions_destination() {
  local dest="$1" state="$2" source="$4" local_override="${1%.md}.local.md"
  case "$state" in
    legacy) rm "$dest" || return ;;
    custom) backup_file "$dest" || return ;;
  esac
  [[ ! -d "$local_override" ]] || backup_file "$local_override" || return
  if [[ "$source" != "$local_override" ]]; then
    [[ ! -L "$local_override" ]] || backup_file "$local_override" || return
    mv "$source" "$local_override" || return
  fi
}

install_instructions() {
  local dest="$1" persona="$2" harness="${3:-}" local_override="${1%.md}.local.md" old="" state=generated local_tmp="" source
  ensure_directory "$(dirname "$dest")"
  if $DRY_RUN; then
    info "Generating $dest from neutral rules"
    return
  fi
  if [[ -L "$dest" ]]; then
    case "$(readlink "$dest")" in
      "$DOTFILES_DIR/.claude/CLAUDE.md"|"$DOTFILES_DIR/.agents/AGENTS.md") state=legacy ;;
      *) state=custom ;;
    esac
  elif [[ -d "$dest" ]] || { [[ -f "$dest" ]] && ! grep -q '^<!-- Generated by dotfiles/install.sh -->$' "$dest"; }; then
    state=custom
  fi
  if [[ "$state" == custom && -f "$dest" ]] && ! grep -q '^<!-- Generated by dotfiles/install.sh -->$' "$dest"; then
    old="$(cat "$dest")" || return
  fi
  source="$local_override"
  if [[ -n "$old" ]]; then
    local_tmp="$(mktemp "${local_override}.tmp.XXXXXX")" || return
    if [[ -f "$local_override" ]]; then
      cat "$local_override" > "$local_tmp" || { rm "$local_tmp"; return 1; }
    fi
    printf '\n%s\n' "$old" >> "$local_tmp" || { rm "$local_tmp"; return 1; }
    source="$local_tmp"
  fi
  if ! install_generated_file "$dest" render_instructions preserve_instructions_destination "$state" "$persona" "$source" "$harness"; then
    [[ -z "$local_tmp" ]] || rm "$local_tmp"
    return 1
  fi
}

install_native_agents() {
  local harness="$1" dir="$2" src name dest template
  case "$harness" in
    claude) ensure_directory "$dir" "$DOTFILES_DIR/.claude/agents" ;;
    opencode) ensure_directory "$dir" "$DOTFILES_DIR/.opencode/agents" ;;
    *) ensure_directory "$dir" ;;
  esac
  for src in "$DOTFILES_DIR"/.agents/agents/_my-*.md; do
    name="$(basename "$src" .md)"
    template=""
    case "$harness" in
      claude|opencode|grok) dest="$dir/$name.md"; template="$DOTFILES_DIR/.$harness/templates/agents/$name.md" ;;
      copilot) dest="$dir/$name.agent.md"; template="$DOTFILES_DIR/.copilot/agents/$name.agent.md" ;;
    esac
    if $DRY_RUN; then
      info "Generating $dest from $src"
      continue
    fi
    install_generated_file "$dest" render_native_agent preserve_generated_destination "$template" "$src" "$template" || return
  done
}

render_native_agent() {
  local src="$1" template="$2"
  cat "$template" || return
  printf '\n<!-- Generated by dotfiles/install.sh -->\n\n'
  markdown_body "$src" || return
}

render_shared_export() {
  local skill
  render_instructions true "" || return
  printf '\n## Skills\n\nLoad each skill file explicitly if the harness has no native skill discovery.\n\n'
  for skill in "$DOTFILES_DIR"/.agents/skills/my-*; do
    printf -- '- `%s`: `%s/SKILL.md`' "$(basename "$skill")" "$HOME/.agents/skills/$(basename "$skill")"
    case "$(basename "$skill")" in
      my-build) printf ' — requires implementation and review subagents with specialist roles.' ;;
      my-security) printf ' — requires an independent read-only security-reviewer role.' ;;
      my-review) printf ' — requires an independent read-only reviewer role.' ;;
      my-plan) printf ' — requires an independent read-only explorer role.' ;;
    esac
    printf '\n'
  done
}

link_skills() {
  local dir="$1" skill
  for skill in "$DOTFILES_DIR"/.agents/skills/my-*; do
    link_file "$skill" "$dir/$(basename "$skill")"
  done
}

install_shared_agents() {
  local src dest="$HOME/.agents/exports/default.md"
  ensure_directory "$HOME/.agents"
  link_file "$DOTFILES_DIR/.agents/AGENTS.md" "$HOME/.agents/AGENTS.md"
  ensure_directory "$HOME/.agents/personas"
  link_file "$DOTFILES_DIR/.agents/personas/my-humble-servant.md" "$HOME/.agents/personas/my-humble-servant.md"
  link_file "$DOTFILES_DIR/.agents/references" "$HOME/.agents/references"
  ensure_directory "$HOME/.agents/agents"
  for src in "$DOTFILES_DIR"/.agents/agents/_my-*.md; do
    link_file "$src" "$HOME/.agents/agents/$(basename "$src")"
  done
  ensure_directory "$HOME/.agents/skills"
  link_skills "$HOME/.agents/skills"
  ensure_directory "$HOME/.agents/exports"
  if $DRY_RUN; then
    info "Generating manual export $dest"
    return
  fi
  install_generated_file "$dest" render_shared_export preserve_generated_destination ""
}

